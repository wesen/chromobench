// - generated/reference.md: the vocabulary, the cuts, the stages (law, medium fields, the layer ops each takes), the
//   mask components, then the handle ops by domain and area, one line per op plus one per argument;
// - generated/instructions.md: the < 4000-character instructions;
// - generated/chromobench-dsl.d.ts: the frame and builder types and one interface per handle domain;
// - src/docs/topics.generated.ts: the topic pages bundled for cb.docs.
import {
  acceptsDomain, CUTS, DOMAIN_NAMES, getLaw, getOp, MASK_COMBINES, MASK_COMPONENT_KINDS, opsForStage, schemas, STAGE_NAMES, STAGES,
  type Domain, type OpDef, type Schema,
} from '@chromobench/contract';
import { dslOps } from '../host.ts';
import { argLines, opLine } from './provider.ts';
import { VOCABULARY } from './vocabulary.ts';

const HEADER = '<!-- GENERATED by tools/gen-docs from the op registry, the stages and packages/dsl/src/docs. Do not edit; run `pnpm gen`. -->';

/** Handle ops a handle of domain `d` has (node ops; layer ops are made with layer()). */
export function opsForDomain(d: Domain): OpDef[] {
  return dslOps().filter((o) => (o.on === 'Image' || o.on === 'Mask') && acceptsDomain(o, d) && (o.on !== 'Mask' || d === 'mask'));
}

/** A schema's fields as dotted paths with their docs. */
function fieldsOf(schema: Schema, prefix: string): { path: string; doc: string }[] {
  const out: { path: string; doc: string }[] = [];
  for (const [k, rule] of Object.entries(schema)) {
    const p = `${prefix}.${k}`;
    const r = rule as unknown as Record<string, unknown>;
    if (typeof r['check'] === 'function') out.push({ path: p, doc: String(r['doc'] ?? '') });
    else if (typeof r['type'] === 'string') {
      const unit = r['unit'] && r['unit'] !== 'none' ? `, ${String(r['unit'])}` : '';
      const values = r['type'] === 'enum' ? ` ${(r['values'] as string[]).join('|')}` : '';
      out.push({ path: p, doc: `${String(r['type'])}${values}${unit} — ${String(r['doc'] ?? '')}` });
    } else out.push(...fieldsOf(rule as Schema, p));
  }
  return out;
}

const cutCall = (name: string): string => (/^\w+$/.test(name) ? `frame.${name}()` : `frame.cut('${name}')`);

export function genReference(): string {
  const out = [HEADER, '', '# Chromobench DSL reference', '',
    'Globals: `cb`, `frame`, `units`, `mem`, `console`; the builders `layer`, `group`, `mask`, `coll`; the changes `set`, `insert`, `remove`, `move`. A frame is a document (format 3: stages with a medium and a stack of layers and groups, a mask library, geometry, output). Its cuts are image handles: lazy nodes of the one compiler; `await` a measurement for numbers. Options are literal values. A what-if is `frame.with(change)`; `frame.propose(change, { why })` submits a change when the eval succeeds.',
    ''];
  out.push('## Vocabulary', '');
  for (const v of VOCABULARY) out.push(`- \`${v.call}\` — ${v.doc}`);
  out.push('', '## Cuts', '', 'Named points of the compiled document, in pipeline order; a frame has those of its kind.', '');
  for (const c of CUTS) out.push(`- \`${cutCall(c.name)}\` → ${c.domain}${c.kinds.length === 1 ? ` (${c.kinds[0]} only)` : ''} — ${c.doc}`);
  out.push('', '## Paths', '',
    'A path is dotted. It starts at an item id (`main.params.time_s`, `sky.feather_mm`: ids are unique in the document and survive moves) or at a root key (`stages.darkroom.medium.paper`, `geometry.crop`). Collections are crossed by item id (`masks.sky.name`); `order` and `items` never appear. A new document has the darkroom entries `main` (expose: time_s, fstop, filtration) and `lights` (filter: logH, the printer lights).',
    '', '- `set(path, value)` sets a field', '- `insert(coll, id, item, at?)` adds an item to a collection: a stack (`stages.print.stack`, `<group>.stack`), the mask library (`masks`), a list argument (`<layer>.params.spots`)',
    '- `remove(id)` deletes an item wherever it is', '- `move(id, { into, at })` reorders it, or moves it into another collection', '');
  out.push('## Stages', '');
  for (const s of STAGE_NAMES) {
    const st = STAGES[s];
    out.push(`### ${s} (${st.kinds.length === 1 ? st.kinds[0] : 'every frame'})`, '', st.doc, '');
    if (st.law) {
      const law = getLaw(st.law);
      out.push(`Law **${law.name}**: amount ${law.amount} in [${law.amountRange.join(', ')}]; ${law.blend ? 'blend modes' : 'no blend modes'}; groups ${law.groups.join(', ')}; order ${law.order}. ${law.doc}`, '');
    } else out.push('No law: the stage takes no entries yet.', '');
    out.push(`Medium (\`stages.${s}.medium\`):`, '');
    for (const f of fieldsOf(schemas().media[s], `stages.${s}.medium`)) out.push(`- \`${f.path}\`: ${f.doc}`);
    const ops = opsForStage(s);
    if (ops.length) {
      out.push('', `Layers (\`insert('stages.${s}.stack', id, layer(op, params))\`):`, '');
      for (const o of ops) {
        out.push(`- \`${opLine(o)}\``);
        for (const l of argLines(o)) out.push(`  - ${l.trim()}`);
      }
    }
    out.push('');
  }
  out.push('## Masks', '', `\`mask(name).add(id, kind, params, combine, amount)\`; combine ${MASK_COMBINES.join(' | ')} (add = max, subtract = a·(1 − b), intersect = a·b); \`.feather(mm)\` on the print; \`.invert()\`; \`.reads(cut)\` (default: the input of the stage that uses it). Geometry in document pixels. An entry uses a mask by id: \`layer(…).mask('sky')\`, after \`insert('masks', 'sky', mask(…))\`.`, '');
  for (const k of MASK_COMPONENT_KINDS) {
    const o = getOp(`mask.${k}`);
    out.push(`- \`${k}\` { ${Object.keys(o.args).join(', ')} } — ${o.doc.split(/(?<=\.)\s/)[0]}`);
    for (const l of argLines(o)) out.push(`  - ${l.trim()}`);
  }
  out.push('', '## Workbench', '', WORKBENCH_REFERENCE, '');
  for (const d of DOMAIN_NAMES) {
    const ops = opsForDomain(d);
    if (!ops.length) continue;
    out.push('', `## Handles in ${d}`, '');
    let area = '';
    for (const o of ops) {
      if (o.area !== area) {
        area = o.area;
        out.push(`- **${area}**`);
      }
      out.push(`  - \`${opLine(o)}\``);
      for (const l of argLines(o)) out.push(`    - ${l.trim()}`);
      if (o.fields?.length) out.push(`    - returns ${o.fields.map((f) => `\`${f.name}\``).join(', ')}`);
    }
  }
  out.push('');
  return out.join('\n');
}

const pascal = (s: string): string => s.split(/[.\-_]/).map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join('');

