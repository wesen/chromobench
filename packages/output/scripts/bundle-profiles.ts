// Regenerates src/icc/profiles/bundled.ts from the .icc files next to it (CC0 Compact ICC Profiles),
// so the profiles load the same way in Node, workers and pages. Run: node packages/output/scripts/bundle-profiles.ts
// test/icc.test.ts checks that bundled.ts matches the files.
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = fileURLToPath(new URL('../src/icc/profiles/', import.meta.url));
const files = readdirSync(dir).filter((f) => f.endsWith('.icc')).sort();
const lines = [
  '// Generated by packages/output/scripts/bundle-profiles.ts from the .icc files in this directory. Do not edit.',
  '// Compact ICC Profiles (github.com/saucecontrol/Compact-ICC-Profiles), CC0 1.0 (LICENSE here).',
  '',
  'export const BUNDLED_PROFILES: Record<string, { sha256: string; base64: string }> = {',
];
for (const f of files) {
  const b = readFileSync(join(dir, f));
  const sha = createHash('sha256').update(b).digest('hex');
  lines.push(`  '${f.replace(/\.icc$/, '')}': { sha256: '${sha}', base64: '${b.toString('base64')}' },`);
}
lines.push('};', '');
writeFileSync(join(dir, 'bundled.ts'), lines.join('\n'));
console.log(`bundled ${files.length} profiles`);
