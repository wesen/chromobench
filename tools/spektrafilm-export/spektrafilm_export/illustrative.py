"""``illustrative@1``: the prototypes' camera and lights, regenerated from their stated parameters.

Nothing here is measured (guide §10). Every item is flagged ``illustrative: true`` and the loader
warns ``W_DATA_ILLUSTRATIVE``. The shapes reproduce Chromogen Studio's ``generic-bayer`` camera and
``white-led`` light (C1 st-data/cg) to its 5-decimal rounding; ``crosscheck`` verifies that.

* generic-bayer: Gaussian R, G, B responsivities, peaks 600 / 535 / 460 nm, FWHM 80 / 90 / 70 nm,
  each scaled to peak 1 ("Gaussian sensitivities peaking near 600, 535 and 460 nm (facts.py)").
* white-led: a 450 nm blue pump (Gaussian, FWHM 22 nm, weight 0.45) plus a phosphor (asymmetric
  Gaussian at 565 nm, sigma 45 nm below and 70 nm above the peak), scaled to peak 1. The parameters
  were recovered by a least-squares fit to Chromogen's tabulated LED (max residual 5.6e-6, i.e. its
  rounding); Chromogen only says "blue pump at 450 nm plus a phosphor (facts.py)".
* led-678/532/472: the Studio's ``xt5-fitted`` scanner LEDs, Gaussian, FWHM 20 nm (assumed by the
  Studio, 05-inline.js 1645-1648).
* led-660/530/450: the textbook's RGB LEDs (``rgb-led-book``), FWHM 20 / 25 / 20 nm.
"""
from __future__ import annotations

import numpy as np

from .packwriter import WAVELENGTHS_NM, PackWriter

# FWHM -> sigma with the prototypes' rounded constant 2.3548 (Chromogen facts.py, core gaussian()), not
# 2*sqrt(2 ln 2) = 2.35482: the exact constant moves the camera curves by 1.1e-5, beyond Chromogen's rounding.
FWHM_TO_SIGMA = 1.0 / 2.3548
WL = WAVELENGTHS_NM

LICENCE_TEXT = """illustrative@1 — licence note
==============================

The spectra in this pack were generated by chromobench (tools/spektrafilm-export/spektrafilm_export/
illustrative.py) from a handful of stated parameters (peak wavelengths and widths of Gaussians). They
contain no measured data and no third-party data, and are not a model of any real product.

Licence: to be set by the project owner (CHB-004 guide §12.4). Until then treat them as project
material that may be redistributed with chromobench.
"""


def gaussian(peak: float, fwhm: float) -> np.ndarray:
    return np.exp(-0.5 * ((WL - peak) / (fwhm * FWHM_TO_SIGMA)) ** 2)


def asym_gaussian(peak: float, sigma_lo: float, sigma_hi: float) -> np.ndarray:
    s = np.where(WL < peak, sigma_lo, sigma_hi)
    return np.exp(-0.5 * ((WL - peak) / s) ** 2)


def camera_generic_bayer() -> np.ndarray:
    return np.stack([gaussian(600, 80), gaussian(535, 90), gaussian(460, 70)], axis=1)


def white_led() -> np.ndarray:
    v = 0.45 * gaussian(450, 22) + asym_gaussian(565, 45, 70)
    return v / v.max()


LEDS = {
    "led-678": (678, 20), "led-532": (532, 20), "led-472": (472, 20),
    "led-660": (660, 20), "led-530": (530, 25), "led-450": (450, 20),
}


def export(packs_root, exporter: str) -> dict:
    w = PackWriter(root=packs_root, pack_id="illustrative@1",
                   title="Illustrative camera and lights (not measured)",
                   source={"kind": "illustrative", "exporter": exporter,
                           "note": "regenerated from stated parameters; see tools/spektrafilm-export/spektrafilm_export/illustrative.py"},
                   license={"spdx": "LicenseRef-chromobench-illustrative", "file": "LICENSE.txt",
                            "attribution": "Illustrative spectra generated by chromobench from stated parameters; not measured."},
                   missing={"default": "opaque", "supported": ["opaque", "zero-density", "extend-flat"]})
    w.text("LICENSE.txt", LICENCE_TEXT)
    cam = {"generic-bayer_rgb_responsivity": camera_generic_bayer()}
    w.tensors("cameras/generic-bayer.safetensors", cam)
    w.item("camera", "generic-bayer", ["cameras/generic-bayer.safetensors"],
           {"tensor": "generic-bayer_rgb_responsivity", "unit": "relPeak", "axes": ["wavelength", "channel R,G,B"],
            "parameters": {"peaks_nm": [600, 535, 460], "fwhm_nm": [80, 90, 70]}},
           cam, tensor="generic-bayer_rgb_responsivity", illustrative=True, measuredRange_nm=None,
           about="Illustrative Bayer camera: Gaussian sensitivities peaking at 600, 535 and 460 nm (FWHM 80, 90, 70 nm). Not a measured camera.")
    lights = {"white-led_spd_relpeak": white_led()}
    lights.update({f"{k}_spd_relpeak": gaussian(p, f) for k, (p, f) in LEDS.items()})
    w.tensors("lights/lights.safetensors", lights)
    w.item("light", "white-led", ["lights/lights.safetensors"],
           {"tensor": "white-led_spd_relpeak", "unit": "relPeak",
            "parameters": {"pump_nm": 450, "pump_fwhm_nm": 22, "pump_weight": 0.45, "phosphor_nm": 565, "phosphor_sigma_lo_nm": 45, "phosphor_sigma_hi_nm": 70}},
           {"white-led_spd_relpeak": lights["white-led_spd_relpeak"]}, tensor="white-led_spd_relpeak", illustrative=True,
           about="Illustrative white LED: blue pump at 450 nm plus a phosphor. Not a measured product.")
    for k, (p, f) in LEDS.items():
        n = f"{k}_spd_relpeak"
        w.item("light", k, ["lights/lights.safetensors"], {"tensor": n, "unit": "relPeak", "parameters": {"peak_nm": p, "fwhm_nm": f}},
               {n: lights[n]}, tensor=n, illustrative=True, about=f"Gaussian LED at {p} nm, FWHM {f} nm (assumed). Not measured.")
    w.extra["scanners"] = {
        "xt5-fitted": {"camera": "generic-bayer", "lights": ["led-678", "led-532", "led-472"], "capture": "sequential"},
        "rgb-led-book": {"camera": "generic-bayer", "lights": ["led-660", "led-530", "led-450"], "capture": "sequential"},
        "white-led": {"camera": "generic-bayer", "lights": ["white-led"], "capture": "single"},
    }
    return w.finish()
