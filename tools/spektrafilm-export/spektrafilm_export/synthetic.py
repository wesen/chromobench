"""Synthetic frames with known truth (guide §11). Only the ``neutral-wedge`` set exists so far.

The generator must not share code with the TypeScript engines, so the truth here comes from a
numpy implementation of the textbook's scanner model (§3.1): a flat (spectrally neutral) density D
transmits T = 10^-D in every channel, and flare adds a fraction f of the open-gate signal,
T' = (T + f) / (1 + f) when the open gate is normalised to 1 (textbook §3.7).

Frame layout (guide §11.3): ``fixtures/synthetic/<set>/<frame>/`` with ``camera_linear.safetensors``
(F32 counts, open gate = 1), ``truth.safetensors`` (F64 truth images) and ``truth.json``.
``splitBucket = int(sha256(group)) mod 100``, so splits stay stable as frames are added.

TODO (stage 5, open): running-six-patch, grey-ramps, scan-conditions, stock-identity and edges need
spektrafilm's own simulate() for the film and print (runtime dependencies beyond the exporter venv),
plus the TIFF/PNG subset for CHB-006.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

import numpy as np

from .packwriter import st_save

STEPS_D = [0.0, 0.5, 1.0, 1.5, 2.0, 2.5, 3.0]
STRIP_W, H = 32, 32


def split_bucket(group: str) -> int:
    return int(hashlib.sha256(group.encode("utf-8")).hexdigest(), 16) % 100


def flare_read(D: np.ndarray, f: float) -> np.ndarray:
    T = 10.0 ** -np.asarray(D, dtype=np.float64)
    return (T + f) / (1.0 + f)


def neutral_wedge(root: Path, exporter: str) -> list[Path]:
    group = "neutral-wedge/flat-0-3D"
    out = []
    for f in (0.0, 0.005):
        frame = f"neutral-wedge/flat-0-3D-flare{round(f * 1000):03d}permille"
        d = root / frame
        d.mkdir(parents=True, exist_ok=True)
        steps = np.array(STEPS_D)
        Tp = flare_read(steps, f)
        cam = np.repeat(np.repeat(Tp, STRIP_W)[None, :, None], H, axis=0).repeat(3, axis=2).astype(np.float32)
        true_D = np.repeat(np.repeat(steps, STRIP_W)[None, :, None], H, axis=0).repeat(3, axis=2)
        md = {"generator": exporter, "frame": frame}
        (d / "camera_linear.safetensors").write_bytes(st_save({"camera_linear": cam}, {**md, "domain": "camera-linear"}))
        (d / "truth.safetensors").write_bytes(st_save({"scanner_density_true": true_D}, {**md, "domain": "scanner-density"}))
        read_D = -np.log10(Tp)
        truth = {
            "id": frame,
            "group": group,
            "splitBucket": split_bucket(group),
            "generator": {"tool": exporter, "model": "flat neutral density; flare T' = (T + f)/(1 + f), open gate = 1 (textbook §3.1, §3.7); no noise",
                          "seed": None, "pack": None},
            "factors": {"flare_fraction": f, "steps_D": STEPS_D},
            "images": {
                "camera_linear": {"file": "camera_linear.safetensors#camera_linear", "domain": "camera-linear", "dtype": "F32", "shape": list(cam.shape)},
                "scanner_density_true": {"file": "truth.safetensors#scanner_density_true", "domain": "scanner-density", "dtype": "F64", "shape": list(true_D.shape)},
            },
            "regions": [
                {"name": f"step{i}", "box": {"x": i * STRIP_W, "y": 0, "w": STRIP_W, "h": H}, "true_D": [float(s)] * 3,
                 "read_D": [float(r)] * 3, "class": "ok"}
                for i, (s, r) in enumerate(zip(steps, read_D))
            ],
            "license": "Generated by chromobench (tools/spektrafilm-export synthetic.py); no third-party data.",
        }
        (d / "truth.json").write_text(json.dumps(truth, indent=1, sort_keys=True) + "\n")
        out.append(d)
    return out
